const (
	ActionRedirectRequest l7policies.Action = "REDIRECT_REQUEST"
	ActionFixedResponse   l7policies.Action = "FIXED_RESPONSE"
	ActionWeightedTargets l7policies.Action = "WEIGHTED_TARGETS"
)

// FixedHTTPResponse is generated by the listener without contacting an application.
type FixedHTTPResponse struct {
	StatusCode int `json:"status_code"`
}

// WeightedHTTPTarget is one ordered destination on an Octavia L7 policy.
type WeightedHTTPTarget struct {
	Weight                  int
	PoolID                  string
	FixedResponse           *FixedHTTPResponse
	RequestHeaderOperations []cloud.HTTPHeaderOperation
	RequestURLRewrite       *RequestURLRewrite
}

func (target WeightedHTTPTarget) HasRequestFilters() bool {
	return len(target.RequestHeaderOperations) != 0 || target.RequestURLRewrite != nil
}

func (target WeightedHTTPTarget) MarshalJSON() ([]byte, error) {
	fields := struct {
		Weight        int                `json:"weight"`
		PoolID        string             `json:"pool_id,omitempty"`
		FixedResponse *FixedHTTPResponse `json:"fixed_response,omitempty"`
		Operations    []map[string]any   `json:"request_header_operations,omitempty"`
		Rewrite       *RequestURLRewrite `json:"request_url_rewrite,omitempty"`
	}{Weight: target.Weight}
	switch {
	case target.PoolID != "" && target.FixedResponse == nil:
		fields.PoolID = target.PoolID
		if len(target.RequestHeaderOperations) != 0 {
			fields.Operations = headerOperationEntries(target.RequestHeaderOperations)
		}
		if target.RequestURLRewrite != nil {
			if !target.RequestURLRewrite.Valid() {
				return nil, fmt.Errorf("invalid weighted policy target URL rewrite")
			}
			fields.Rewrite = target.RequestURLRewrite
		}
	case target.PoolID == "" && target.FixedResponse != nil && !target.HasRequestFilters():
		fields.FixedResponse = target.FixedResponse
	default:
		return nil, fmt.Errorf("weighted policy target must select one destination and can only filter requests forwarded to a pool")
	}
	return json.Marshal(fields)
}

// UnmarshalJSON checks the two mutually exclusive target forms defined by Octavia.
// A missing weight must remain distinguishable from a deliberately disabled slot.
func (target *WeightedHTTPTarget) UnmarshalJSON(data []byte) error {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	var weight *int
	if json.Unmarshal(fields["weight"], &weight) != nil ||
		weight == nil || *weight < 0 || *weight > 1_000_000 {
		return fmt.Errorf("weighted policy target requires a weight from 0 to 1000000 and one destination")
	}
	decoded := WeightedHTTPTarget{Weight: *weight}
	delete(fields, "weight")
	switch {
	case fields["pool_id"] != nil:
		if err := json.Unmarshal(fields["pool_id"], &decoded.PoolID); err != nil || decoded.PoolID == "" {
			return fmt.Errorf("weighted policy target has an invalid pool ID")
		}
		delete(fields, "pool_id")
		if raw, ok := fields[requestHeaderOperationsField]; ok {
			operations, err := readPolicyHeaderOperations(raw, requestHeaderOperationsField)
			if err != nil {
				return err
			}
			decoded.RequestHeaderOperations = operations
			delete(fields, requestHeaderOperationsField)
		}
		if raw, ok := fields[requestURLRewriteField]; ok {
			decoded.RequestURLRewrite = readRequestURLRewrite(raw)
			if decoded.RequestURLRewrite == nil {
				return fmt.Errorf("invalid weighted policy target URL rewrite")
			}
			delete(fields, requestURLRewriteField)
		}
	case fields["fixed_response"] != nil:
		var response map[string]int
		if err := json.Unmarshal(fields["fixed_response"], &response); err != nil {
			return err
		}
		code := response["status_code"]
		if len(response) != 1 || code != http.StatusNotFound && code != http.StatusInternalServerError {
			return fmt.Errorf("weighted policy fixed response requires a single status_code of 404 or 500")
		}
		decoded.FixedResponse = &FixedHTTPResponse{StatusCode: code}
		delete(fields, "fixed_response")
	default:
		return fmt.Errorf("weighted policy target has no recognized destination")
	}
	if len(fields) != 0 {
		return fmt.Errorf("weighted policy target has unexpected fields")
	}
	*target = decoded
	return nil
}

// L7PolicyTarget preserves the distinctions between null, absent and concrete
// response fields which are lost in the upstream SDK's policy type.
type L7PolicyTarget struct {
	RedirectPool    json.RawMessage      `json:"redirect_pool_id"`
	FixedResponse   *FixedHTTPResponse   `json:"fixed_response"`
	WeightedTargets []WeightedHTTPTarget `json:"targets"`
	AdminStateUp    *bool                `json:"admin_state_up"`
}

func (target L7PolicyTarget) IsFixedServerError() bool {
	return string(target.RedirectPool) == "null" && target.FixedResponse != nil &&
		target.FixedResponse.StatusCode == http.StatusInternalServerError
}

// L7PolicyObservation keeps readable pool references even when another field
// prevents the entire target from decoding.
type L7PolicyObservation struct {
	Policy                      l7policies.L7Policy
	HTTPSListenerHostname       string
	Target                      *L7PolicyTarget
	ExtendedTargetFields        bool
	TCPTLSPassthrough           *bool
	ActivationOptions           string
	HTTPRequestPolicy           *cloud.HTTPRequestPolicy
	HTTPRequestPolicyReported   bool
	HTTPRequestPolicyPresent    bool
	TargetRequestFiltersPresent bool
	RedirectRequest             *RequestRedirect
	RedirectRequestPresent      bool
	RequestURLRewrite           *RequestURLRewrite
	RequestURLRewriteReported   bool
	RequestCORS                 *cloud.HTTPCORS
	RequestCORSPresent          bool
	RequestCORSReported         bool
	RequestURLRewritePresent    bool
	PoolIDs                     []string
	PoolReference               json.RawMessage
	AdminState                  *bool
	RequestHeaderOperations     []cloud.HTTPHeaderOperation
	RequestHeaderOperationsErr  error
	ResponseHeaderOperations    []cloud.HTTPHeaderOperation
	ResponseHeaderOperationsErr error
}

// ListPolicyObservations retains every policy row across explicit API pages.
// A stock 204 can stand for an empty response but cannot complete an extended
// policy inventory. JSON responses must contain an explicit collection.
func (s *Service) ListPolicyObservations(ctx context.Context, opts l7policies.ListOpts) ([]L7PolicyObservation, bool, error) {
	var observations []L7PolicyObservation
	complete := true
	err := eachCollectionPage(ctx, l7policies.List(s.client, opts), func(result pagination.PageResult) pagination.Page {
		return policyObservationPage{l7PolicyPage(result).(l7policies.L7PolicyPage)}
	}, func(page pagination.Page) error {
		policyPage := page.(policyObservationPage)
		if policyPage.StatusCode == http.StatusNoContent {
			complete = false
			return nil
		}
		var response struct {
			Policies []json.RawMessage `json:"l7policies"`
		}
		if err := policyPage.ExtractInto(&response); err != nil {
			return err
		}
		if response.Policies == nil {
			return missingCollection("l7policies")
		}
		for _, raw := range response.Policies {
			observation, err := readPolicyObservation(raw)
			if err != nil {
				return err
			}
			observations = append(observations, observation)
		}
		return nil
	})
	return observations, complete, err
}

func readPolicyObservation(raw json.RawMessage) (L7PolicyObservation, error) {
	var row struct {
		l7policies.L7Policy
		HTTPSListenerHostname    json.RawMessage `json:"https_listener_hostname"`
		AdminState               *bool           `json:"admin_state_up"`
		PoolReference            json.RawMessage `json:"redirect_pool_id"`
		TCPTLSPassthrough        json.RawMessage `json:"tcp_tls_passthrough"`
		Targets                  json.RawMessage `json:"targets"`
		FixedResponse            json.RawMessage `json:"fixed_response"`
		RedirectRequest          json.RawMessage `json:"redirect_request"`
		RequestURLRewrite        json.RawMessage `json:"request_url_rewrite"`
		HTTPRequestPolicy        json.RawMessage `json:"http_request_policy"`
		RequestCORS              json.RawMessage `json:"request_cors"`
		RequestHeaderOperations  json.RawMessage `json:"request_header_operations"`
		ResponseHeaderOperations json.RawMessage `json:"response_header_operations"`
	}
	if err := json.Unmarshal(raw, &row); err != nil {
		return L7PolicyObservation{}, fmt.Errorf("extract L7 policy: %w", err)
	}
	if strings.TrimSpace(row.ID) == "" {
		return L7PolicyObservation{}, fmt.Errorf("L7 policy row does not report an ID")
	}
	observation := L7PolicyObservation{Policy: row.L7Policy, PoolReference: row.PoolReference, AdminState: row.AdminState}
	switch string(row.TCPTLSPassthrough) {
	case "false":
		observation.TCPTLSPassthrough = new(false)
	case "true":
		observation.TCPTLSPassthrough = new(true)
	}
	if len(row.HTTPSListenerHostname) != 0 {
		// A string is the only positive section proof. Keep the owning policy
		// identifiable even when the endpoint cannot report a valid scope.
		_ = json.Unmarshal(row.HTTPSListenerHostname, &observation.HTTPSListenerHostname)
	}
	observation.ActivationOptions = policyActivationOptions(row.HTTPSListenerHostname, row.Targets, row.FixedResponse,
		row.RedirectRequest, row.RequestURLRewrite, row.RequestCORS, row.RequestHeaderOperations, row.ResponseHeaderOperations, row.HTTPRequestPolicy)
	if row.AdminState != nil {
		observation.Policy.AdminStateUp = *row.AdminState
	}
	if len(row.PoolReference) != 0 {
		if err := json.Unmarshal(row.PoolReference, &observation.Policy.RedirectPoolID); err != nil {
			return L7PolicyObservation{}, fmt.Errorf("extract L7 policy pool relationship: %w", err)
		}
	}
	if len(row.Targets) > 0 {
		var slots []json.RawMessage
		err := json.Unmarshal(row.Targets, &slots)
		observation.ExtendedTargetFields = err != nil || len(slots) > 0
		for _, rawSlot := range slots {
			var slot map[string]json.RawMessage
			if json.Unmarshal(rawSlot, &slot) != nil {
				continue
			}
			observation.TargetRequestFiltersPresent = observation.TargetRequestFiltersPresent ||
				slot[requestHeaderOperationsField] != nil || slot[requestURLRewriteField] != nil
			var poolID string
			if json.Unmarshal(slot["pool_id"], &poolID) == nil && strings.TrimSpace(poolID) != "" {
				observation.PoolIDs = append(observation.PoolIDs, poolID)
			}
		}
	}
	if len(row.FixedResponse) != 0 && string(row.FixedResponse) != "null" {
		observation.ExtendedTargetFields = true
	}
	if len(row.RedirectRequest) != 0 && string(row.RedirectRequest) != "null" {
		observation.RedirectRequestPresent = true
		observation.RedirectRequest = readRequestRedirect(row.RedirectRequest)
	}
	observation.RequestURLRewriteReported = row.RequestURLRewrite != nil
	if observation.RequestURLRewriteReported && string(row.RequestURLRewrite) != "null" {
		observation.RequestURLRewritePresent = true
		observation.RequestURLRewrite = readRequestURLRewrite(row.RequestURLRewrite)
	}
	observation.HTTPRequestPolicyReported = row.HTTPRequestPolicy != nil
	observation.HTTPRequestPolicyPresent = observation.HTTPRequestPolicyReported && string(row.HTTPRequestPolicy) != "null"
	if observation.HTTPRequestPolicyPresent {
		observation.HTTPRequestPolicy = readHTTPRequestPolicy(row.HTTPRequestPolicy)
	}
	observation.RequestCORSReported = row.RequestCORS != nil
	if observation.RequestCORSReported && string(row.RequestCORS) != "null" {
		observation.RequestCORSPresent = true
		observation.RequestCORS = readRequestCORS(row.RequestCORS)
	}
	if row.RequestHeaderOperations != nil {
		observation.RequestHeaderOperations, observation.RequestHeaderOperationsErr =
			readPolicyHeaderOperations(row.RequestHeaderOperations, requestHeaderOperationsField)
	}
	if row.ResponseHeaderOperations != nil {
		observation.ResponseHeaderOperations, observation.ResponseHeaderOperationsErr =
			readPolicyHeaderOperations(row.ResponseHeaderOperations, responseHeaderOperationsField)
	}
	var target L7PolicyTarget
	if json.Unmarshal(raw, &target) == nil {
		observation.Target = &target
	}
	return observation, nil
}

