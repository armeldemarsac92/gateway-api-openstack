func completePolicyPage(result pagination.PageResult) pagination.Page {
	if result.StatusCode == http.StatusNoContent {
		result.Body = map[string]any{"l7policies": []any{}}
	}
	return l7policies.L7PolicyPage{LinkedPageBase: pagination.LinkedPageBase{PageResult: result}}
}

const (
	ActionFixedResponse   l7policies.Action = "FIXED_RESPONSE"
	ActionWeightedTargets l7policies.Action = "WEIGHTED_TARGETS"
)

// FixedHTTPResponse is generated by the listener without contacting an application.
type FixedHTTPResponse struct {
	StatusCode int `json:"status_code"`
}

// WeightedHTTPTarget is one ordered destination on an Octavia L7 policy.
type WeightedHTTPTarget struct {
	Weight        int                `json:"weight"`
	PoolID        string             `json:"pool_id,omitempty"`
	FixedResponse *FixedHTTPResponse `json:"fixed_response,omitempty"`
}

// UnmarshalJSON checks the two mutually exclusive target forms defined by Octavia.
// A missing weight must remain distinguishable from a deliberately disabled slot.
func (target *WeightedHTTPTarget) UnmarshalJSON(data []byte) error {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	var weight *int
	if len(fields) != 2 || json.Unmarshal(fields["weight"], &weight) != nil ||
		weight == nil || *weight < 0 || *weight > 1_000_000 {
		return fmt.Errorf("weighted policy target requires a weight from 0 to 1000000 and one destination")
	}
	decoded := WeightedHTTPTarget{Weight: *weight}
	switch {
	case fields["pool_id"] != nil:
		if err := json.Unmarshal(fields["pool_id"], &decoded.PoolID); err != nil || decoded.PoolID == "" {
			return fmt.Errorf("weighted policy target has an invalid pool ID")
		}
	case fields["fixed_response"] != nil:
		var response map[string]int
		if err := json.Unmarshal(fields["fixed_response"], &response); err != nil {
			return err
		}
		code := response["status_code"]
		if len(response) != 1 || code != http.StatusNotFound && code != http.StatusInternalServerError {
			return fmt.Errorf("weighted policy fixed response requires a single status_code of 404 or 500")
		}
		decoded.FixedResponse = &FixedHTTPResponse{StatusCode: code}
	default:
		return fmt.Errorf("weighted policy target has no recognized destination")
	}
	*target = decoded
	return nil
}

// L7PolicyTarget preserves the distinctions between null, absent and concrete
// response fields which are lost in the upstream SDK's policy type.
type L7PolicyTarget struct {
	RedirectPool    json.RawMessage      `json:"redirect_pool_id"`
	FixedResponse   *FixedHTTPResponse   `json:"fixed_response"`
	WeightedTargets []WeightedHTTPTarget `json:"targets"`
	AdminStateUp    *bool                `json:"admin_state_up"`
}

func (target L7PolicyTarget) IsFixedServerError() bool {
	return string(target.RedirectPool) == "null" && target.FixedResponse != nil &&
		target.FixedResponse.StatusCode == http.StatusInternalServerError && target.AdminStateUp != nil
}

// L7PolicyObservation keeps readable pool references even when another field
// prevents the entire target from decoding.
type L7PolicyObservation struct {
	Policy                     l7policies.L7Policy
	Target                     *L7PolicyTarget
	ExtendedTargetFields       bool
	PoolIDs                    []string
	PoolReference              json.RawMessage
	AdminState                 *bool
	RequestHeaderOperations    []cloud.HTTPHeaderOperation
	RequestHeaderOperationsErr error
}

// ListPolicyObservations retains every policy row across explicit API pages.
// A stock 204 can stand for an empty response but cannot complete an extended
// policy inventory. JSON responses must contain an explicit collection.
func (s *Service) ListPolicyObservations(ctx context.Context, opts l7policies.ListOpts) ([]L7PolicyObservation, bool, error) {
	var observations []L7PolicyObservation
	complete := true
	err := eachCollectionPage(ctx, l7policies.List(s.client, opts), func(result pagination.PageResult) pagination.Page {
		return policyObservationPage{l7PolicyPage(result).(l7policies.L7PolicyPage)}
	}, func(page pagination.Page) error {
		policyPage := page.(policyObservationPage)
		if policyPage.StatusCode == http.StatusNoContent {
			complete = false
			return nil
		}
		var response struct {
			Policies []json.RawMessage `json:"l7policies"`
		}
		if err := policyPage.ExtractInto(&response); err != nil {
			return err
		}
		if response.Policies == nil {
			return missingCollection("l7policies")
		}
		for _, raw := range response.Policies {
			observation, err := readPolicyObservation(raw)
			if err != nil {
				return err
			}
			observations = append(observations, observation)
		}
		return nil
	})
	return observations, complete, err
}

func readPolicyObservation(raw json.RawMessage) (L7PolicyObservation, error) {
	var row struct {
		l7policies.L7Policy
		AdminState              *bool           `json:"admin_state_up"`
		PoolReference           json.RawMessage `json:"redirect_pool_id"`
		Targets                 json.RawMessage `json:"targets"`
		FixedResponse           json.RawMessage `json:"fixed_response"`
		RequestHeaderOperations json.RawMessage `json:"request_header_operations"`
	}
	if err := json.Unmarshal(raw, &row); err != nil {
		return L7PolicyObservation{}, fmt.Errorf("extract L7 policy: %w", err)
	}
	if strings.TrimSpace(row.ID) == "" {
		return L7PolicyObservation{}, fmt.Errorf("L7 policy row does not report an ID")
	}
	observation := L7PolicyObservation{Policy: row.L7Policy, PoolReference: row.PoolReference, AdminState: row.AdminState}
	if row.AdminState != nil {
		observation.Policy.AdminStateUp = *row.AdminState
	}
	if len(row.PoolReference) != 0 {
		if err := json.Unmarshal(row.PoolReference, &observation.Policy.RedirectPoolID); err != nil {
			return L7PolicyObservation{}, fmt.Errorf("extract L7 policy pool relationship: %w", err)
		}
	}
	if len(row.Targets) > 0 {
		var slots []json.RawMessage
		err := json.Unmarshal(row.Targets, &slots)
		observation.ExtendedTargetFields = err != nil || len(slots) > 0
		for _, rawSlot := range slots {
			var slot struct {
				PoolID string `json:"pool_id"`
			}
			if json.Unmarshal(rawSlot, &slot) == nil && strings.TrimSpace(slot.PoolID) != "" {
				observation.PoolIDs = append(observation.PoolIDs, slot.PoolID)
			}
		}
	}
	if len(row.FixedResponse) != 0 && string(row.FixedResponse) != "null" {
		observation.ExtendedTargetFields = true
	}
	if row.RequestHeaderOperations != nil {
		observation.RequestHeaderOperations, observation.RequestHeaderOperationsErr =
			readPolicyRequestHeaderOperations(row.RequestHeaderOperations)
	}
	var target L7PolicyTarget
	if json.Unmarshal(raw, &target) == nil {
		observation.Target = &target
	}
	return observation, nil
}

type policyObservationPage struct{ l7policies.L7PolicyPage }

func (page policyObservationPage) NextPageURL() (string, error) {
	if page.StatusCode == http.StatusNoContent {
		return "", nil
	}
	return page.L7PolicyPage.NextPageURL()
}

func l7PolicyPage(result pagination.PageResult) pagination.Page {
	return l7policies.L7PolicyPage{LinkedPageBase: pagination.LinkedPageBase{PageResult: result}}
}

type fixedResponsePolicyOpts struct {
	l7policies.CreateOpts
}

func (opts fixedResponsePolicyOpts) ToL7PolicyCreateMap() (map[string]any, error) {
	body, err := opts.CreateOpts.ToL7PolicyCreateMap()
	if err != nil {
		return nil, err
	}
	setPolicyFixedServerError(body)
	return body, nil
}

func (fixedResponsePolicyOpts) ToL7PolicyUpdateMap() (map[string]any, error) {
	body := map[string]any{"l7policy": map[string]any{}}
	setPolicyFixedServerError(body)
	return body, nil
}

func setPolicyFixedServerError(body map[string]any) {
	policy := body["l7policy"].(map[string]any)
	policy["action"] = string(ActionFixedResponse)
	policy["fixed_response"] = map[string]int{"status_code": http.StatusInternalServerError}
}

// CreateFixedResponsePolicy creates a policy for an unresolved Service reference.
func (s *Service) CreateFixedResponsePolicy(ctx context.Context, opts l7policies.CreateOpts) (*l7policies.L7Policy, error) {
	opts.Action, opts.RedirectPoolID = ActionFixedResponse, ""
	return l7policies.Create(ctx, s.client, fixedResponsePolicyOpts{opts}).Extract()
}

// SetPolicyFixedResponse switches the target without changing state or position.
func (s *Service) SetPolicyFixedResponse(ctx context.Context, id string, operations []cloud.HTTPHeaderOperation) (*l7policies.L7Policy, error) {
	return s.UpdatePolicyRequestHeaders(ctx, id, fixedResponsePolicyOpts{}, operations)
}

type weightedPolicyOpts struct {
	l7policies.CreateOpts
	targets    []WeightedHTTPTarget
	operations []cloud.HTTPHeaderOperation
}

func (opts weightedPolicyOpts) ToL7PolicyCreateMap() (map[string]any, error) {
	body, err := opts.CreateOpts.ToL7PolicyCreateMap()
	if err != nil {
		return nil, err
	}
	body["l7policy"].(map[string]any)["targets"] = opts.targets
	writePolicyRequestHeaderOperations(body, opts.operations)
	return body, nil
}

func (opts weightedPolicyOpts) ToL7PolicyUpdateMap() (map[string]any, error) {
	return map[string]any{"l7policy": map[string]any{"action": ActionWeightedTargets, "targets": opts.targets}}, nil
}

// CreateWeightedPolicy creates a policy with independent weights per destination.
func (s *Service) CreateWeightedPolicy(ctx context.Context, opts l7policies.CreateOpts, targets []WeightedHTTPTarget, operations []cloud.HTTPHeaderOperation) (*l7policies.L7Policy, error) {
	opts.Action, opts.RedirectPoolID = ActionWeightedTargets, ""
	return l7policies.Create(ctx, s.client, weightedPolicyOpts{CreateOpts: opts, targets: targets, operations: operations}).Extract()
}

// SetPolicyWeightedTargets replaces all slots in one request, retaining the policy position and state.
func (s *Service) SetPolicyWeightedTargets(ctx context.Context, id string, targets []WeightedHTTPTarget, operations []cloud.HTTPHeaderOperation) (*l7policies.L7Policy, error) {
	return s.UpdatePolicyRequestHeaders(ctx, id, weightedPolicyOpts{targets: targets}, operations)
}

// CreatePolicy creates one L7 policy.
